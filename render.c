void dibujar_fondo(Cfg cfg)
{
    int tam = 8;
    for(int y = 0; y < cfg.alto; y += tam)
    {
        for(int x = 0; x < cfg.ancho; x += tam)
        {
            int id = (x/tam + y/tam) % 3;
            uint8_t color;
            if(id == 0)
                color = 0;
            else if(id == 1)
                color = 1;
            else
                color = 2;

            for(int i = 0; i < tam; i++)
            {
                for(int j = 0; j < tam; j++)
                {
                    gbt_dibujar_pixel(x + j, y + i, color);
                }
            }

        }
    }
}
