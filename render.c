void dibujar_bloque(uint16_t x, uint16_t y, int color)
{
    uint16_t pixel_x = x * TAM_BLOQUE;
    uint16_t pixel_y = y * TAM_BLOQUE;

     for(int i = 0; i < TAM_BLOQUE; i++)
     {
        for(int j = 0; j < TAM_BLOQUE; j++)
        {
            gbt_dibujar_pixel(pixel_x + j, pixel_y + i, color);
        }
     }
}
void dibujar_tablero(int** board,Tetrimino* p, EstadoJuego* estado)
{
    int i, j;

    gbt_borrar_backbuffer(0);

    for(i = 0; i < FIL_BOARD; i++)
    {
        for(j = 0; j < COL_BOARD; j++)
        {
            if(board[i][j] == 1)
            {
                dibujar_bloque(j, i, C);
            }
        }
    }

    for(i = 0; i < TAM_TETRIMINO; i++)
    {
        for(j = 0; j < TAM_TETRIMINO; j++)
        {
            if(p->forma[i][j] == 1)
            {
                dibujar_bloque(
                    p->pos_x + j,
                    p->pos_y + i,
                    A
                );
            }
        }
    }

    char buffer[32];

    sprintf(buffer, "Score %d", estado->puntos);
    dibujar_texto_8x8(90, 10, buffer, 14);

    sprintf(buffer, "Nivel %d", estado->piezas_caidas / PIEZAS_POR_NIVEL + 1);
    dibujar_texto_8x8(90, 25, buffer, 14);

    sprintf(buffer, "Vel %dms", (int)estado->velocidad_ms);
    dibujar_texto_8x8(90, 40, buffer, 14);

    gbt_volcar_backbuffer();

    gbt_volcar_backbuffer();
}

void dibujar_texto_8x8(uint16_t x, uint16_t y, const char* texto, uint8_t color)
{
    uint16_t cx = x;
    while(*texto != '\0')
    {
        unsigned char c = (unsigned char)*texto;
        if(c < 123)
        {
            for(int i = 0; i < 8; i++)
                for(int j = 0; j < 8; j++)
                    if(FUENTE_8x8[c][i][j])
                        gbt_dibujar_pixel(cx + j, y + i, color);
        }
        cx += 8;
        texto++;
    }
}

